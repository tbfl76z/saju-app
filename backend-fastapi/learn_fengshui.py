from __future__ import annotations

import fengshui_engine as fe

_GRID = [["巽", "離", "坤"], ["震", "中", "兌"], ["艮", "坎", "乾"]]


def _chart_table(sitting: str, period: int) -> str:
    """비성반을 md 표로 (남상 배치, 셀=산성·향성, 아래 운반)."""
    c = fe.star_chart(sitting, period)
    lines = ["| 남동 | 남 | 남서 |", "|---|---|---|"]
    for row in _GRID:
        cells = []
        for g in row:
            mark = ""
            if g == fe.MOUNTAIN_INFO[c["sitting"]]["palace"]:
                mark = " 坐"
            elif g == fe.MOUNTAIN_INFO[c["facing"]]["palace"]:
                mark = " 向"
            cells.append(f"**{c['mountain'][g]}·{c['water'][g]}** ⌄{c['base'][g]}{mark}")
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    lines.append(f"({period}운 {c['sitting']}山{c['facing']}向 · **{c['structure']}** — 각 칸: 산성·향성, ⌄운반)")
    return "\n".join(lines)


def _structure_table(period: int) -> str:
    """해당 운의 24좌향 격국 일람 md 표."""
    rows = ["| 좌(坐) | 향(向) | 격국 |", "|---|---|---|"]
    for m in fe.MOUNTAINS_24:
        c = fe.star_chart(m, period)
        rows.append(f"| {m} | {c['facing']} | {c['structure']} |")
    return "\n".join(rows)


