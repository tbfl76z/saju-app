def _special_tags(gz: str, branch: str) -> list[str]:
    tags = []
    if gz in _GOIGANG:
        tags.append("**괴강(魁罡)** — 극과 극의 기운. 총명하고 결단력이 크나 파란도 큰 대인형")
    if gz in _BAEKHO:
        tags.append("**백호대살** — 강렬한 에너지. 전문 기술·활인업으로 쓰면 큰 힘이 되는 살")
    if gz in _ILIN:
        tags.append("**일인(양인일주)** — 칼 같은 추진력. 승부처에서 빛나되 과격함은 경계")
    if gz in _GANYEO:
        tags.append("**간여지동** — 천간·지지가 같은 기운. 뚝심이 굳고 배우자와 기 싸움 주의")
    if branch in _DOHWA:
        tags.append("일지 **도화** — 사람을 끄는 매력")
    if branch in _YEOKMA:
        tags.append("일지 **역마** — 이동·변화 속에 기회")
    if branch in _HWAGAE:
        tags.append("일지 **화개** — 학문·예술·정신세계의 깊이")
    return tags


def _build_cards() -> list[dict]:
    cards = [{
        "title": "일주론이란",
        "body": ("**일주(日柱)**는 태어난 날의 간지로, 사주의 주인공인 **나 자신**과 "
                 "**배우자궁(일지)**을 담습니다. 60갑자 일주마다 고유한 성격의 골격이 있어, "
                 "일주만 제대로 읽어도 그 사람의 절반을 본다고 합니다.\n\n"
                 "각 카드는 **일지의 십신·12운성·지장간·특수살**로 구성했습니다. "
                 "같은 일주라도 나머지 여섯 글자에 따라 발현이 달라지니, 골격으로 이해하세요."),
    }]
    for i in range(60):
        stem, branch = STEMS[i % 10], BRANCHES[i % 12]
        gz = stem + branch
        sp = _SIP_KO[sipsin(stem, BRANCH_MAIN[branch])]
        us = TWELVE_GROWTH[stem][branch]
        tags = _special_tags(gz, branch)
        tag_txt = ("\n\n" + "\n".join(f"- {t}" for t in tags)) if tags else ""
        body = (
            f"**물상**: {_STEM_IMG[stem]}({stem})가 {_BRANCH_IMG[branch]}({branch}) 위에 앉은 형상.\n\n"
            f"**일지 {sp} · {us}** — {_SIP_MEAN[sp]} 12운성으로는 {_UNSEONG_MEAN[us]}.\n\n"
            f"**일지 지장간**: {_JIJANGGAN[branch]}"
            f"{tag_txt}"
        )
        cards.append({
            "title": f"{gz}({_STEM_KO[stem]}{_BRANCH_KO[branch]}) 일주",
            "body": body,
        })
    return cards


