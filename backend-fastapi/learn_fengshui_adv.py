from __future__ import annotations

import fengshui_engine as fe

_G8 = ["坎", "坤", "震", "巽", "乾", "兌", "艮", "離"]
_DIR = fe.PALACE_DIR


def _fanfu(sit: str, period: int) -> str | None:
    """전국 반음·복음 판정 — 오황 입중 순비=복음 / 역비=반음."""
    c = fe.star_chart(sit, period)
    for key in ("mountain", "water"):
        b = c[key]
        if all(b[g] == fe.PALACE_NUM[g] for g in _G8):
            return f"{'산성' if key == 'mountain' else '향성'} 전국 복음"
        if all(b[g] + fe.PALACE_NUM[g] == 10 for g in _G8):
            return f"{'산성' if key == 'mountain' else '향성'} 전국 반음"
    return None


def _fanfu_table() -> str:
    """전국 반음·복음 24국씩 — 좌향별 성립 운 표."""
    rows: dict[tuple[str, str], list[int]] = {}
    for p in range(1, 10):
        for m in fe.MOUNTAINS_24:
            r = _fanfu(m, p)
            if r:
                rows.setdefault((m, r), []).append(p)
    fu = sorted([(m, ps) for (m, r), ps in rows.items() if "복음" in r])
    fan = sorted([(m, ps) for (m, r), ps in rows.items() if "반음" in r])
    def fmt(lst):
        return " / ".join(f"{m}坐({'·'.join(str(p) + '운' for p in ps)})" for m, ps in lst)
    return (f"**전국 복음 24국**\n\n{fmt(fu)}\n\n"
            f"**전국 반음 24국**\n\n{fmt(fan)}")


def _earth_luck_table() -> str:
    """지운(地運) 8구간 — 향이 놓인 궁만으로 결정됨."""
    off = {g: i for i, g in enumerate(fe.FLY_ORDER)}
    seen: dict[str, list[str]] = {}
    for m in fe.MOUNTAINS_24:
        fp = fe.MOUNTAIN_INFO[fe.opposite_mountain(m)]["palace"]
        seen.setdefault(fp, []).append(m)
    lines = ["| 향이 놓인 궁 | 좌산 | 지운 |", "|---|---|---|"]
    for g, ms in sorted(seen.items(), key=lambda kv: off[kv[0]]):
        lines.append(f"| {g}({_DIR[g]}) | {'·'.join(ms)}山 | **{20 * off[g]}년** |")
    return "\n".join(lines)


def _samban_table() -> str:
    """부모삼반괘 성립 좌향 — 전수 계산."""
    out: dict[str, list[int]] = {}
    for p in range(1, 10):
        for m in fe.MOUNTAINS_24:
            c = fe.star_chart(m, p)
            ok = True
            for g in _G8 + ["中"]:
                s = {c["base"][g], c["mountain"][g], c["water"][g]}
                if len(s) != 3 or len({x % 3 for x in s}) != 1:
                    ok = False
                    break
            if ok:
                out.setdefault(m, []).append(p)
    lines = ["| 좌산 | 성립 운 |", "|---|---|"]
    for m, ps in sorted(out.items()):
        lines.append(f"| {m}山{fe.opposite_mountain(m)}向 | **{'·'.join(str(p) + '운' for p in ps)}** |")
    return "\n".join(lines)


def _period9_note() -> str:
    """9운 격국 분포 — 왕산왕향·상산하수가 없다."""
    from collections import Counter
    res = {m: fe.star_chart(m, 9)["structure"] for m in fe.MOUNTAINS_24}
    cnt = Counter(res.values())
    body = " / ".join(f"{k} {v}국" for k, v in cnt.items())
    return f"**9운 24좌향 격국 분포: {body}**"


